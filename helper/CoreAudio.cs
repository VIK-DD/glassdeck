// Minimal COM interop for Windows Core Audio (MMDevice API, endpoint volume, audio sessions).
// Interfaces list every vtable slot in order; slots we never call are declared as plain placeholders.
using System.Runtime.InteropServices;

namespace Glassdeck.Helper;

internal enum EDataFlow { Render = 0, Capture = 1 }

internal enum ERole { Console = 0, Multimedia = 1, Communications = 2 }

internal enum AudioSessionState { Inactive = 0, Active = 1, Expired = 2 }

internal static class DeviceState
{
    public const uint Active = 0x1;
}

[StructLayout(LayoutKind.Sequential)]
internal struct PropertyKey
{
    public Guid FormatId;
    public int PropertyId;

    public static readonly PropertyKey DeviceFriendlyName = new()
    {
        FormatId = new Guid("a45c254e-df1c-4efd-8020-67d146a850e0"),
        PropertyId = 14,
    };
}

/// <summary>PROPVARIANT, laid out for 64-bit (24 bytes). Only the string case (VT_LPWSTR) is read.</summary>
[StructLayout(LayoutKind.Explicit, Size = 24)]
internal struct PropVariant
{
    [FieldOffset(0)] public ushort ValueType;
    [FieldOffset(8)] public IntPtr Pointer;

    private const ushort VtLpwstr = 31;

    public string? AsString() => ValueType == VtLpwstr ? Marshal.PtrToStringUni(Pointer) : null;
}

internal static class Ole32
{
    [DllImport("ole32.dll")]
    public static extern int PropVariantClear(ref PropVariant value);
}

